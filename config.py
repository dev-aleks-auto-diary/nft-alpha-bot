# ── Фильтры качества (применяются на нескольких контрольных точках) ───
# Вместо одной проверки в фиксированный момент — несколько чекпоинтов
# с разным балансом "скорость vs уверенность". Кандидата проверяем на
# каждом чекпоинте по очереди, пока он либо не пройдёт (шлём алерт и
# останавливаемся), либо не закончатся чекпоинты (тогда молча отбрасываем).
#
# Ранний чекпоинт с низким порогом ловит вирусные проекты, которые
# распродаются за минуты и не успели бы набрать много минтеров к более
# позднему чекпоинту. Поздние чекпоинты с более высоким порогом дают шанс
# медленно набирающим обороты, но реально качественным проектам — им
# нужно больше времени, зато и планка выше, чтобы это не превращалось
# в фильтр "пропускай всё подряд, если подождать достаточно долго".
#
# Формат: (задержка в секундах от первого минта, минимум уникальных минтеров)
CHECKPOINTS = [
    (900, 5),        # 15 минут — вирусный хайп заметен почти сразу
    (3600, 15),       # 1 час
    (21600, 40),      # 6 часов
    (86400, 100),     # 24 часа — последний шанс, порог заметно выше
]

# Минимальная цена минта в ETH. 0 — фильтр выключен. Проверяется на
# любом чекпоинте одинаково (от времени не зависит).
MIN_MINT_PRICE_ETH = 0.001

